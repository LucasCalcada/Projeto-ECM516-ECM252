  const ComplaintStrings._(this.languageCode);

  factory ComplaintStrings.forLanguage(String code) {
    final language = code.toLowerCase().split(RegExp('[-_]')).first;
    return ComplaintStrings._(
      _translations.containsKey(language) ? language : 'pt',
    );
  }

  final String languageCode;

  String text(String key) =>
      _translations[languageCode]?[key] ?? _translations['pt']?[key] ?? key;

  String date(DateTime value) {
    final local = value.toLocal();
    final day = local.day.toString().padLeft(2, '0');
    final month = local.month.toString().padLeft(2, '0');
    final year = local.year.toString().padLeft(4, '0');
    return languageCode == 'en' ? '$month/$day/$year' : '$day/$month/$year';
  }

